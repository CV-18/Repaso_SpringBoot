DROP TABLE IF EXISTS USER_ROLES;
DROP TABLE IF EXISTS ALBUMES;
DROP TABLE IF EXISTS USUARIOS;
DROP TABLE IF EXISTS DISCOGRAFICAS;

CREATE TABLE DISCOGRAFICAS (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(20) NOT NULL UNIQUE,
  is_deleted BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE ALBUMES (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    anio INT NOT NULL,
    banda VARCHAR(255) NOT NULL,
    genero VARCHAR(255) NOT NULL,
    precio DOUBLE NOT NULL,
    discografica_id BIGINT,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    uuid UUID NOT NULL UNIQUE
);

CREATE TABLE USUARIOS (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   nombre VARCHAR(255) NOT NULL,
   apellidos VARCHAR(255) NOT NULL,
   username VARCHAR(255) NOT NULL UNIQUE,
   email VARCHAR(255) NOT NULL UNIQUE,
   password VARCHAR(255) NOT NULL,
   discografica_id BIGINT,
   is_deleted BOOLEAN DEFAULT FALSE,
   created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
   updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE USER_ROLES (
   user_id BIGINT NOT NULL,
   roles ENUM ('ADMIN', 'USER')
);

ALTER TABLE ALBUMES
    ADD CONSTRAINT fk_albumes_discograficas
        FOREIGN KEY (discografica_id) REFERENCES DISCOGRAFICAS(id);

ALTER TABLE USER_ROLES
    ADD CONSTRAINT fk_user_roles_usuarios
        FOREIGN KEY (user_id) REFERENCES USUARIOS(id);

ALTER TABLE USUARIOS
    ADD CONSTRAINT fk_usuarios_discograficas
        FOREIGN KEY (discografica_id) REFERENCES DISCOGRAFICAS(id);